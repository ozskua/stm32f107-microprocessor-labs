/* USER CODE BEGIN PFP */
typedef struct{
	uint8_t Type;
	uint8_t Lenght;
	uint8_t data[100];
	uint32_t received_id;
	uint8_t check;
}gelen_packet;

gelen_packet g_msg;
void Protocol_ParseByte(uint8_t *a, int len){
	uint8_t BCC = BCC_INIT_VALUE;
	int i;

	g_msg.Type = a[1];
	g_msg.Lenght = a[2];

	//XOR
	for(i=0; i<(len-2); i++){
		BCC ^= a[i+1];
	}

	if(BCC != a[len-1]){
		//gelen paket bozuk
		return;
	}

	for(i = 0; i < g_msg.Lenght; i++){
		g_msg.data[i] = a[i+3]; // a[3]'ten itibaren data baslar
	}

	// byteları birleştime (öğrenci numarası)
	g_msg.received_id = ((uint32_t)g_msg.data[0] << 24) |
	                    ((uint32_t)g_msg.data[1] << 16) |
	                    ((uint32_t)g_msg.data[2] << 8)  |
	                     (uint32_t)g_msg.data[3];

	if(g_msg.received_id == STUDENT_NO){ //KONTROL
		g_msg.check = 1;
	}else{
		g_msg.check = 0;
	}
}
